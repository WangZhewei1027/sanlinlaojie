import assert from "node:assert/strict";
import { setTransform, moveKeys, deleteKeys, keyTimes, minimumDuration } from "@/lib/scene/editor-document";
import { instanceValues, stateFromDefinition } from "@/lib/scene/theatre-state";
import { createBlankScene, type CompositionInstance } from "@/lib/scene/protocol";
import { parseSceneText } from "@/lib/scene/validate";
const original: CompositionInstance = { id: "box", asset: "model", position: [0, 0, 0], quaternion: [0, 0, 0, 1], scale: [1, 1, 1], animation: null };
const rotated = setTransform(original, "rotation.y", Math.PI / 2, 0, false);
assert.ok(Math.abs(instanceValues(rotated).rotation.y - Math.PI / 2) < 0.00001);
assert.equal(rotated.tracks, undefined);
const animated = setTransform(original, "position.x", 4, 2, true);
assert.deepEqual(keyTimes(animated), [0, 2]);
assert.equal(animated.tracks!["position.x"]![0].value, 0, "recording later preserves initial pose");
const custom = structuredClone(animated);
custom.tracks!["position.x"]![1].handles = [0.1, 0.3, 0.8, 0.6];
custom.tracks!["position.x"]![1].connectedRight = false;
const changed = setTransform(custom, "position.x", 6, 2, false);
assert.deepEqual(changed.tracks!["position.x"]![1].handles, [0.1, 0.3, 0.8, 0.6]);
assert.equal(changed.tracks!["position.x"]![1].connectedRight, false);
const moved = moveKeys(changed, "position", 2, 4);
assert.deepEqual(keyTimes(moved), [0, 4]);
assert.deepEqual(moved.tracks!["position.x"]![1].handles, [0.1, 0.3, 0.8, 0.6]);
const removed = deleteKeys(moved, "position", 4);
assert.deepEqual(keyTimes(removed), [0]);
assert.deepEqual(original.position, [0, 0, 0], "history snapshot remains immutable");
const definition = createBlankScene();
definition.content.assets = {model:{assetId:"11111111-1111-4111-8111-111111111111"}};
definition.content.instances = [moved];
assert.equal(minimumDuration(definition), 4);
assert.deepEqual(parseSceneText(JSON.stringify(definition)), definition);
const track = stateFromDefinition(definition).sheetsById.Scene.sequence.tracksByObject.box as {trackData: Record<string, {keyframes: {position:number;handles:number[]}[]}>};
assert.equal(track.trackData.position_x.keyframes[1].position, 4);
assert.deepEqual(track.trackData.position_x.keyframes[1].handles, [0.1, 0.3, 0.8, 0.6]);
console.log("PASS static rotation, record initial pose, preserve Bezier/hold edits, move/delete keys, immutable history and portable state round trip");
